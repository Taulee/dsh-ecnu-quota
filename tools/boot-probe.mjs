#!/usr/bin/env node
/**
 * Offline boot self-check for a DSH Desktop profile.
 *
 * Boots a *copy* of the real desktop profile through the exact code path the
 * Desktop Host uses (`loadProfileDirectory` + `runProfile`), inside a scratch
 * `DSH_HOME` and on a spare port, then reports everything a running app hides:
 * skipped bundles, entries that failed to import, the client bundles injected
 * into `window.__DSH_BOOT__`, and the HTTP status of the plugin routes.
 *
 * The real profile is never written to: only `package.json`,
 * `cordis.patch.yml` and `pnpm-workspace.yaml` are copied and `node_modules` is
 * symlinked, because `composeProfile` rewrites `cordis.yml` on every boot.
 *
 * Run it with the application's own Electron binary in Node mode (the plugins
 * live inside `app.asar`, which only Electron's patched `fs` can read):
 *
 *   ELECTRON_RUN_AS_NODE=1 "/Applications/DeepSeek Harness.app/Contents/MacOS/DeepSeek Harness" \
 *     tools/boot-probe.mjs
 *
 * Flags: `--app` bundle path · `--profile` profile directory · `--port` spare
 * port · `--home` scratch home · `--grep` substring reported from the boot
 * entries · `--route` extra route to probe (repeatable) · `--hold` seconds to
 * keep serving for a browser check · `--url-out` file receiving the
 * token-authenticated URL.
 *
 * A probed route answering 200 with `"status":"missing-credential"` is the
 * expected result here: the scratch home has no credential store, so this check
 * covers wiring (activation, route, injected client bundle), not the upstream
 * call. Export `ECNUCHAT_API_KEY` in the environment to exercise the real
 * upstream instead — the boot inherits `process.env` as its first credential
 * source, and the real store is never touched.
 *
 * Exit codes: 0 every probed route answered 200 · 1 the profile did not boot ·
 * 2 the profile booted but at least one probed route did not answer 200.
 *
 * @module dsh-ecnu-quota/tools/boot-probe
 */

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

/** Copy these profile files; `cordis.yml` is regenerated by the boot itself. */
const PROFILE_FILES = ["package.json", "cordis.patch.yml", "pnpm-workspace.yaml"];

/** Route probed after boot unless `--route` adds others. */
const DEFAULT_ROUTES = ["/plugins/dsh-ecnu-quota/quota"];

/**
 * Read one `--name value` argument.
 * @param argv - argument vector.
 * @param name - flag name without dashes.
 * @param fallback - value when the flag is absent.
 * @returns the flag value.
 */
function flag(argv, name, fallback) {
	const at = argv.indexOf(`--${name}`);
	return at >= 0 && argv[at + 1] !== void 0 ? argv[at + 1] : fallback;
}

/**
 * Read every repeated `--name value` argument.
 * @param argv - argument vector.
 * @param name - flag name without dashes.
 * @returns the values, in argv order.
 */
function flags(argv, name) {
	const values = [];
	for (let at = 0; at < argv.length; at += 1) {
		if (argv[at] === `--${name}` && argv[at + 1] !== void 0) values.push(argv[at + 1]);
	}
	return values;
}

const argv = process.argv.slice(2);
const home = process.env.HOME ?? "";
const appPath = flag(argv, "app", "/Applications/DeepSeek Harness.app");
const runtimeDir = join(appPath, "Contents", "Resources", "app.asar", "dsh");
const installAnchor = join(runtimeDir, "node_modules", "@deepseek-ai", "dsh", "package.json");
const sourceProfile = flag(argv, "profile", join(home, ".dsh", "profiles", "desktop"));
const port = flag(argv, "port", "19399");
const probeHome = flag(argv, "home", join(tmpdir(), "dsh-boot-probe-home"));
const needle = flag(argv, "grep", "ecnu");
const routes = [...DEFAULT_ROUTES, ...flags(argv, "route")];
const holdMs = Number(flag(argv, "hold", "0")) * 1000;
const urlOut = flag(argv, "url-out", "");

/** Print one diagnostic line. */
function say(message) {
	process.stdout.write(`[probe] ${message}\n`);
}

if (!existsSync(installAnchor)) {
	say(`cannot find the DSH installation under ${appPath}`);
	say("run this script with the app's Electron binary: ELECTRON_RUN_AS_NODE=1 \"…/DeepSeek Harness\"");
	process.exit(1);
}
if (!existsSync(join(sourceProfile, "package.json"))) {
	say(`no profile manifest at ${sourceProfile}`);
	process.exit(1);
}

// Stage the profile copy: the boot rewrites cordis.yml, so it must not be the live directory.
const staged = join(probeHome, "profiles", "probe");
rmSync(staged, { recursive: true, force: true });
mkdirSync(staged, { recursive: true });
for (const file of PROFILE_FILES) {
	const from = join(sourceProfile, file);
	if (existsSync(from)) cpSync(from, join(staged, file));
}
const modules = join(sourceProfile, "node_modules");
if (existsSync(modules)) symlinkSync(modules, join(staged, "node_modules"), "dir");
say(`staged ${staged} from ${sourceProfile} (node_modules symlinked)`);

process.env.DSH_HOME = probeHome;
mkdirSync(probeHome, { recursive: true });

// Never point the real credential store at the scratch home: the boot writes a browser-session record into
// whatever store it finds. Keys reach this probe through the environment instead (see the docstring).

const manifest = JSON.parse(readFileSync(join(staged, "package.json"), "utf8"));
say(`bundles=${(manifest.dsh?.profile?.bundles ?? []).join(",")}`);

const { loadLayeredEnv, loadProfileDirectory, reportSkippedBundles } = await import(
	join(runtimeDir, "node_modules", "@deepseek-ai", "dsh-app-boot", "lib", "index.js")
);
const { runProfile } = await import(join(runtimeDir, "node_modules", "@deepseek-ai", "dsh", "lib", "profile-boot.js"));

const profile = loadProfileDirectory("dsh", staged, installAnchor);
say(`skippedBundles=${JSON.stringify(profile.skippedBundles)}`);
reportSkippedBundles("dsh", profile);

const app = await runProfile({
	environment: loadLayeredEnv("dsh"),
	profile: "desktop",
	resolvedProfile: { profile, installAnchor },
	patchFiles: [],
	args: ["--no-open", "--port", port]
}).catch((error) => {
	say(`BOOT FAILED: ${String(error)}`);
	process.exit(1);
});

const ctx = app.ctx;
say(`booted on port ${String(ctx.webServer?.port)} · credentials=${ctx.get("credentials") === void 0 ? "absent" : "present"}`);

// The client half rides in the boot injections; a host entry that fails to import takes it down too.
try {
	const injections = ctx.webServer.collectIndexInjections();
	const boot = injections.find((entry) => entry.kind === "global" && entry.name === "__DSH_BOOT__");
	const entries = boot?.value?.entries ?? [];
	say(`__DSH_BOOT__ rev=${String(boot?.value?.rev)} entries=${entries.length}`);
	for (const entry of entries) {
		if (entry.id.toLowerCase().includes(needle.toLowerCase())) say(`boot entry: ${JSON.stringify(entry)}`);
	}
	const preload = injections.filter((entry) => entry.kind === "script-preload").map((entry) => entry.src ?? "");
	say(`preload lists ${needle}: ${String(preload.some((src) => src.toLowerCase().includes(needle.toLowerCase())))}`);
} catch (error) {
	say(`injection dump failed: ${String(error)}`);
}

let failures = 0;
for (const route of routes) {
	try {
		const response = await fetch(`http://127.0.0.1:${port}${route}`, { headers: { accept: "application/json" } });
		const body = await response.text();
		if (response.status !== 200) failures += 1;
		say(`${route} -> ${response.status} ${body.slice(0, 300)}`);
	} catch (error) {
		failures += 1;
		say(`${route} -> ERROR ${String(error)}`);
	}
}

// The authenticated URL is only written to a file (or stdout when no file is asked for) — it carries a launch token.
let authenticatedUrl;
try {
	authenticatedUrl = ctx.connection.authenticatedUrl(`http://127.0.0.1:${String(ctx.webServer.port)}`);
	if (urlOut !== "") writeFileSync(urlOut, authenticatedUrl, { mode: 0o600 });
	else say(`authenticated url: ${authenticatedUrl}`);
} catch (error) {
	say(`could not build the authenticated url: ${String(error)}`);
}

// `--hold` keeps the instance serving so an external browser (Chrome --headless --dump-dom) can inspect the real UI.
if (holdMs > 0) {
	say(`holding for ${holdMs / 1000}s for browser inspection at ${authenticatedUrl === void 0 ? "(unknown url)" : authenticatedUrl.replace(/\?.*$/u, "/?token=…")}`);
	await new Promise((resolve) => setTimeout(resolve, holdMs));
	say("hold finished");
	// The boot forks workers that outlive the event loop, so never wait for a quiet exit here.
	setTimeout(() => process.exit(failures === 0 ? 0 : 2), 8_000);
}

await app.shutdown.shutdown(0);
say(failures === 0 ? "PROBE OK: every probed route answered 200" : `PROBE FAILED: ${failures} route(s) did not answer 200`);
process.exit(failures === 0 ? 0 : 2);
